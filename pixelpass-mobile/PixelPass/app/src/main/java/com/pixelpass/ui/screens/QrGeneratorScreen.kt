package com.pixelpass.ui.screens

import androidx.compose.foundation.Image
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.ArrowBack
import androidx.compose.material.icons.filled.Person
import androidx.compose.material.icons.filled.QrCode
import androidx.compose.material.icons.filled.Refresh
import androidx.compose.material.icons.filled.Shield
import androidx.compose.material.icons.outlined.Schedule
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextAlign
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import kotlinx.coroutines.delay
import com.pixelpass.ui.theme.*
import com.pixelpass.utils.generateQrCode

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun QrGeneratorScreen(
    token: String,
    onBackClick: () -> Unit = {},
    onProfileClick: () -> Unit = {}
) {
    // State to toggle between placeholder and active QR code
    var isQrGenerated by remember { mutableStateOf(false) }

    // 15 minute expiration countdown for the time-bound token
    var timeLeft by remember { mutableIntStateOf(15 * 60) }
    val qrBitmap = remember(token) { generateQrCode(token) }

    // Timer only runs when the QR code is actively generated
    LaunchedEffect(key1 = isQrGenerated, key2 = timeLeft) {
        if (isQrGenerated && timeLeft > 0) {
            delay(1000L)
            timeLeft--
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.Center,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Box(
                            modifier = Modifier
                                .padding(end = 8.dp)
                                .size(28.dp)
                                .background(PrimaryBlue, RoundedCornerShape(8.dp)),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.Shield,
                                contentDescription = "Security Shield",
                                tint = SurfaceWhite,
                                modifier = Modifier.size(16.dp)
                            )
                        }
                        Text(
                            text = "Qr Generator",
                            style = AppTypography.headlineMedium.copy(fontSize = 22.sp)
                        )
                    }
                },
                navigationIcon = {
                    IconButton(onClick = onBackClick) {
                        Icon(
                            imageVector = Icons.Default.ArrowBack,
                            contentDescription = "Back",
                            tint = NeutralDark
                        )
                    }
                },
                actions = {
                    IconButton(
                        onClick = onProfileClick,
                        modifier = Modifier.padding(end = 8.dp)
                    ) {
                        Box(
                            modifier = Modifier
                                .size(36.dp)
                                .clip(CircleShape)
                                .background(PrimaryBlue),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.Person,
                                contentDescription = "Profile",
                                tint = SurfaceWhite,
                                modifier = Modifier.size(20.dp)
                            )
                        }
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = SurfaceLight)
            )
        },
        containerColor = SurfaceLight
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            // Main QR Card
            Card(
                modifier = Modifier
                    .fillMaxWidth()
                    .aspectRatio(0.85f),
                colors = CardDefaults.cardColors(containerColor = SurfaceWhite),
                shape = RoundedCornerShape(24.dp),
                elevation = CardDefaults.cardElevation(defaultElevation = 2.dp)
            ) {
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(24.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.Center
                ) {
                    Text(
                        text = "● LIVE QR PREVIEW",
                        color = if (isQrGenerated) Color(0xFF10B981) else Color.LightGray,
                        fontWeight = FontWeight.Bold,
                        fontSize = 12.sp,
                        letterSpacing = 1.sp
                    )

                    Spacer(modifier = Modifier.height(24.dp))

                    // Toggle between the generated Matrix and the SVG Placeholder
                    if (isQrGenerated && qrBitmap != null) {
                        Image(
                            bitmap = qrBitmap,
                            contentDescription = "Access QR Code",
                            modifier = Modifier.size(200.dp)
                        )
                    } else {
                        // Standard Material Icon acting as the placeholder graphic
                        Icon(
                            imageVector = Icons.Default.QrCode,
                            contentDescription = "QR Placeholder",
                            tint = Color(0xFFE2E8F0), // Subtle grey-blue matching SurfaceLight theme
                            modifier = Modifier.size(200.dp)
                        )
                    }

                    Spacer(modifier = Modifier.height(24.dp))

                    // Expiry Timer
                    Surface(
                        color = if (isQrGenerated) Color(0xFFEEF2FF) else SurfaceLight,
                        shape = RoundedCornerShape(16.dp)
                    ) {
                        val minutes = timeLeft / 60
                        val seconds = timeLeft % 60

                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.Center,
                            modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Outlined.Schedule,
                                contentDescription = "Timer",
                                tint = if (isQrGenerated) PrimaryBlue else Color.Gray,
                                modifier = Modifier.size(16.dp).padding(end = 4.dp)
                            )
                            Text(
                                text = String.format("Expires in\n%02d:%02d", minutes, seconds),
                                color = if (isQrGenerated) PrimaryBlue else Color.Gray,
                                fontWeight = FontWeight.Medium,
                                fontSize = 14.sp,
                                textAlign = TextAlign.Center
                            )
                        }
                    }
                }
            }

            Spacer(modifier = Modifier.weight(1f))

            // Action Button
            Button(
                onClick = {
                    isQrGenerated = true
                    timeLeft = 15 * 60 // Fresh 15-minute timer
                },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(56.dp),
                enabled = !isQrGenerated, // Grey out once generated
                colors = ButtonDefaults.buttonColors(
                    containerColor = PrimaryBlue,
                    disabledContainerColor = Color(0xFFE2E8F0),
                    disabledContentColor = Color.Gray
                ),
                shape = RoundedCornerShape(12.dp)
            ) {
                Icon(
                    imageVector = Icons.Default.Refresh,
                    contentDescription = null,
                    modifier = Modifier.padding(end = 8.dp)
                )
                Text(
                    text = "Generate QR Code",
                    style = AppTypography.bodyLarge.copy(
                        color = if (isQrGenerated) Color.Gray else SurfaceWhite
                    )
                )
            }

            Text(
                text = "Generates a fresh encrypted authentication session",
                fontSize = 13.sp,
                color = Color.Gray,
                modifier = Modifier.padding(top = 16.dp)
            )

            Spacer(modifier = Modifier.height(24.dp))

            Text(
                text = "Secured with 256-bit encryption. Privacy Policy · Terms",
                fontSize = 12.sp,
                color = Color.Gray,
                modifier = Modifier.padding(bottom = 16.dp)
            )
        }
    }
}